def css_width(scale: str) -> str:
    raw = BORDER_WIDTHS[scale]
    return "0" if raw == "0" else f"{raw}px"


def css_number_width(value: int | float | str) -> str:
    if isinstance(value, (int, float)):
        return "0" if value == 0 else f"{value:g}px"
    return value


def points_width(value: str) -> str:
    return value.removesuffix("px") if value.endswith("px") else value


def dp_width(value: str) -> str:
    raw = points_width(value)
    return f"{raw}.dp"


def escape_swift(value: str) -> str:
    return value.replace("\\", "\\\\").replace('"', '\\"')


def escape_kotlin(value: str) -> str:
    return escape_swift(value)


def escape_ts(value: str) -> str:
    return escape_swift(value)


def write_file(path: Path, content: str, check: bool) -> bool:
    path.parent.mkdir(parents=True, exist_ok=True)
    normalized = content.rstrip() + "\n"
    if check:
        current = path.read_text() if path.exists() else ""
        if current != normalized:
            print(f"DIFF {path}")
            for line in difflib.unified_diff(
                current.splitlines(),
                normalized.splitlines(),
                fromfile=str(path),
                tofile=f"{path} (generated)",
                lineterm="",
            ):
                print(line)
            return False
        return True
    path.write_text(normalized)
    return True


def generate(
    project_root: Path,
    platform: str,
    theme_slug: str,
    package_name: str,
    check: bool,
    output: Path | None = None,
) -> bool:
    tokens = read_theme(theme_slug)
    project_root = project_root.resolve()

    outputs = {
        "swift": (project_root / "styling.gen.swift", swift(tokens)),
        "kotlin": (project_root / "styling.gen.kt", kotlin(tokens, package_name)),
        "typescript": (project_root / "styling.gen.ts", typescript(tokens)),
    }

    path, content = outputs[platform]
    if output is not None:
        path = output if output.is_absolute() else project_root / output
    return write_file(path, content, check)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("project_root", nargs="?", default=".", help="Project root to receive generated files.")
    parser.add_argument(
        "--platform",
        required=True,
        choices=("swift", "kotlin", "typescript"),
        help="Platform styling file to generate.",
    )
    parser.add_argument(
        "--theme",
        default="light",
        help="Theme JSON under themes/ to use, without the .json suffix. Defaults to light.",
    )
    parser.add_argument(
        "--kotlin-package",
        default="com.designarchitect.designsystem",
        help="Package name for styling.gen.kt.",
    )
    parser.add_argument(
        "--check",
        action="store_true",
        help="Print diffs and fail if generated files are stale.",
    )
    parser.add_argument(
        "--output",
        type=Path,
        help="Optional generated-file path, relative to project root unless absolute.",
    )
    args = parser.parse_args()

    try:
        ok = generate(
            Path(args.project_root),
            args.platform,
            args.theme,
            args.kotlin_package,
            args.check,
            args.output,
        )
    except ValueError as error:
        print(f"error: {error}", file=sys.stderr)
        return 2

    if args.check and not ok:
        return 1

    verb = "Checked" if args.check else "Generated"
    print(f"{verb} {args.platform} design system for theme '{args.theme}' in {Path(args.project_root).resolve()}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
