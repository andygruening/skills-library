def raw_group(data: object, key: str) -> dict[str, object]:
    if isinstance(data, dict) and isinstance(data.get(key), dict):
        return data[key]
    return {}


def int_value(value: object, fallback: int) -> int:
    if isinstance(value, int):
        return value
    if isinstance(value, float):
        return int(value)
    return fallback


def first_int(value: object, fallback: int) -> int:
    if isinstance(value, list) and value:
        return int_value(value[0], fallback)
    return int_value(value, fallback)


def str_value(value: object, fallback: str = "") -> str:
    if isinstance(value, str):
        return value
    if isinstance(value, (int, float)):
        return f"{value:g}"
    return fallback


def typography_heading_weight(tokens: ThemeTokens) -> int:
    product = raw_group(tokens.typography_tokens, "product")
    return int_value(product.get("boldWeight"), 700)


def typography_body_weight(tokens: ThemeTokens) -> int:
    product = raw_group(tokens.typography_tokens, "product")
    return int_value(product.get("bodyWeight"), 500)


def typography_line_height(tokens: ThemeTokens) -> str:
    product = raw_group(tokens.typography_tokens, "product")
    value = product.get("lineHeight")
    if isinstance(value, (int, float)):
        return f"{value:g}"
    return "1.2"


def ts_literal(value: object) -> str:
    return json.dumps(value, indent=2, sort_keys=True)


def indent_ts(value: str, spaces: int) -> str:
    lines = value.splitlines()
    if len(lines) <= 1:
        return value
    padding = " " * spaces
    return lines[0] + "\n" + "\n".join(padding + line for line in lines[1:])


def resolve_design_ref(value: object, tokens: ThemeTokens, fallback: str) -> str:
    if not isinstance(value, str):
        return fallback
    resolved = resolve_ref_path(value, tokens)
    if isinstance(resolved, str):
        return resolved
    return value


def resolve_design_style(value: object, tokens: ThemeTokens, fallback: str) -> str:
    if not isinstance(value, str):
        return fallback

    def replace(match: re.Match[str]) -> str:
        resolved = resolve_ref_path(match.group(0), tokens)
        return resolved if isinstance(resolved, str) else match.group(0)

    return re.sub(r"\b[a-zA-Z][a-zA-Z0-9]*\.[a-zA-Z][a-zA-Z0-9]*\b", replace, value)


def resolve_ref_path(path: str, tokens: ThemeTokens) -> object:
    if "." not in path:
        return None
    head, *parts = path.split(".")
    roots: dict[str, object] = {
        "background": raw_group(tokens.color_tokens, "background"),
        "foreground": raw_group(tokens.color_tokens, "foreground"),
        "border": raw_group(tokens.color_tokens, "border"),
        "brand": raw_group(tokens.color_tokens, "brand"),
        "button": raw_group(tokens.color_tokens, "button"),
        "semantic": raw_group(tokens.color_tokens, "semantic"),
        "colors": tokens.color_tokens,
        "radii": tokens.radii_tokens,
        "shadows": tokens.shadow_tokens,
        "motion": tokens.motion_tokens,
    }
    current = roots.get(head)
