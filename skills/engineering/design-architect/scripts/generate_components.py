def audit_rich_theme_payload(data: dict[str, object], payload: dict[str, object]) -> None:
    source_paths = set(leaf_paths({section: data[section] for section in RICH_THEME_SECTIONS}))
    emitted_paths = set(leaf_paths(payload))
    missing_paths = sorted(source_paths - emitted_paths)
    if missing_paths:
        preview = ", ".join(missing_paths[:8])
        raise ValueError(f"Rich theme payload is missing schema values: {preview}.")


def leaf_paths(value: object, prefix: str = "") -> list[str]:
    if isinstance(value, dict):
        paths: list[str] = []
        for key, child in value.items():
            child_prefix = f"{prefix}.{key}" if prefix else str(key)
            paths.extend(leaf_paths(child, child_prefix))
        return paths
    if isinstance(value, list):
        paths: list[str] = []
        for index, child in enumerate(value):
            paths.extend(leaf_paths(child, f"{prefix}[{index}]"))
        return paths or [prefix]
    return [prefix]


def validate_theme_json(data: object, path: Path, expected_slug: str | None = None) -> None:
    if not isinstance(data, dict):
        raise ValueError(f"{path} must contain a JSON object.")

    required_top = ("id", "name", "description", "typography", "colors", "components")
    require_keys(data, required_top, path)

    if expected_slug is not None and data["id"] != expected_slug:
        raise ValueError(f"{path} id must match its directory name '{expected_slug}'.")

    for key in ("id", "name", "description"):
        if not isinstance(data[key], str) or not data[key].strip():
            raise ValueError(f"{path} field '{key}' must be a non-empty string.")

    typography = require_object(data, "typography", path)
    require_keys(typography, ("fontFamily", "headingWeight", "bodyWeight", "lineHeight"), path / "typography")
    if not isinstance(typography["fontFamily"], str) or not typography["fontFamily"].strip():
        raise ValueError(f"{path} typography.fontFamily must be a non-empty string.")
    for key in ("headingWeight", "bodyWeight"):
        if not isinstance(typography[key], int):
            raise ValueError(f"{path} typography.{key} must be an integer.")
    if not isinstance(typography["lineHeight"], (int, float)):
        raise ValueError(f"{path} typography.lineHeight must be a number.")

    colors = require_object(data, "colors", path)
    require_keys(colors, HEX_COLOR_FIELDS, path / "colors")
    for key in HEX_COLOR_FIELDS:
        if not is_hex_color(colors[key]):
            raise ValueError(f"{path} colors.{key} must be a #RRGGBB or #RRGGBBAA color.")

    components = require_object(data, "components", path)
    require_keys(components, ("boxBorders", "labelBorders", "buttonBorders"), path / "components")
    for key in ("boxBorders", "labelBorders", "buttonBorders"):
        if components[key] not in BORDER_SCALES:
            raise ValueError(f"{path} components.{key} must be one of: {', '.join(BORDER_SCALES)}.")


def is_rich_theme_json(data: object) -> bool:
    return isinstance(data, dict) and isinstance(data.get("spacing"), dict) and isinstance(data.get("radii"), dict)


def validate_rich_theme_json(data: object, path: Path, expected_slug: str | None = None) -> None:
    if not isinstance(data, dict):
        raise ValueError(f"{path} must contain a JSON object.")

    require_keys(
        data,
        (
            "id",
            "name",
            "description",
            "colors",
            "typography",
            "spacing",
            "radii",
            "borders",
            "shadows",
            "motion",
            "components",
        ),
        path,
    )

    if expected_slug is not None and data["id"] != expected_slug:
        raise ValueError(f"{path} id must match its directory name '{expected_slug}'.")

    for key in ("id", "name", "description"):
        if not isinstance(data[key], str) or not data[key].strip():
            raise ValueError(f"{path} field '{key}' must be a non-empty string.")

    colors = require_object(data, "colors", path)
    for key in ("brand", "background", "foreground", "border", "button", "semantic"):
        require_object(colors, key, path / "colors")

    brand = colors["brand"]
    require_color_keys(brand, ("default", "hover", "ring", "surface", "border"), path / "colors" / "brand")

    background = colors["background"]
    require_color_keys(
        background,
        ("page", "canvas", "surface", "surfaceHover", "surfaceSelected", "surfaceInverse", "search", "searchActive", "searchSelected"),
        path / "colors" / "background",
    )

    foreground = colors["foreground"]
    require_color_keys(
        foreground,
        ("primary", "secondary", "tertiary", "disabled", "inverse", "link", "linkHover"),
        path / "colors" / "foreground",
    )

    border = colors["border"]
    require_keys(border, ("default", "subtle", "hover", "strongHover", "focus", "divider"), path / "colors" / "border")
    for key in ("default", "subtle", "hover", "strongHover", "focus"):
        if not is_hex_color(border[key]):
            raise ValueError(f"{path} colors.border.{key} must be a #RRGGBB or #RRGGBBAA color.")

    button = colors["button"]
    require_color_keys(
        button,
        (
            "primaryBg",
            "primaryText",
            "primaryHoverBg",
            "primaryActiveBg",
            "secondaryBg",
            "secondaryText",
            "secondaryBorder",
            "secondaryHoverBorder",
            "secondaryActiveBg",
            "secondaryActiveBorder",
            "disabledBg",
            "disabledText",
        ),
        path / "colors" / "button",
    )

    semantic = colors["semantic"]
    for key in ("info", "success", "warning"):
        group = require_object(semantic, key, path / "colors" / "semantic")
        require_color_keys(group, ("bg", "fg", "border"), path / "colors" / "semantic" / key)
    danger = require_object(semantic, "danger", path / "colors" / "semantic")
    require_color_keys(danger, ("bg", "fg", "border", "buttonBg", "buttonHoverBg", "buttonActiveBg"), path / "colors" / "semantic" / "danger")

    typography = require_object(data, "typography", path)
    product = require_object(typography, "product", path / "typography")
    require_keys(product, ("family", "bodyWeight", "boldWeight", "lineHeight"), path / "typography" / "product")

    radii = require_object(data, "radii", path)
    for key in ("button", "input", "badge", "card"):
        if not isinstance(radii.get(key), int):
            raise ValueError(f"{path} radii.{key} must be an integer.")

    borders = require_object(data, "borders", path)
    if not isinstance(borders.get("defaultWidth"), int):
        raise ValueError(f"{path} borders.defaultWidth must be an integer.")


def require_color_keys(data: dict[str, object], keys: tuple[str, ...], path: Path) -> None:
    require_keys(data, keys, path)
    for key in keys:
        if not is_hex_color(data[key]):
            raise ValueError(f"{path}.{key} must be a #RRGGBB or #RRGGBBAA color.")


def require_object(data: dict[str, object], key: str, path: Path) -> dict[str, object]:
    value = data[key]
    if not isinstance(value, dict):
        raise ValueError(f"{path} field '{key}' must be an object.")
    return value


def require_keys(data: dict[str, object], keys: tuple[str, ...] | list[str], path: Path) -> None:
    missing = [key for key in keys if key not in data]
    if missing:
        raise ValueError(f"{path} is missing required fields: {', '.join(missing)}.")


def is_hex_color(value: object) -> bool:
    if not isinstance(value, str):
        return False
    raw = value.removeprefix("#")
    return value.startswith("#") and len(raw) in (6, 8) and all(char in "0123456789abcdefABCDEF" for char in raw)


